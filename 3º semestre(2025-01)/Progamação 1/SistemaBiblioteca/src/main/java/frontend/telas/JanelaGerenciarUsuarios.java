    private void botaoExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoExcluirActionPerformed
        int linhaSelecionada = tabelaUsuarios.getSelectedRow();

        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, selecione um usuário na tabela para excluir.", "Nenhum Usuário Selecionado", JOptionPane.WARNING_MESSAGE);
        } else {
            int resposta = JOptionPane.showConfirmDialog(this, "Tem a certeza que deseja excluir o usuário selecionado?", "Confirmar Exclusão", JOptionPane.YES_NO_OPTION);

            if (resposta == JOptionPane.YES_OPTION) {
                Long idParaExcluir = (Long) modeloTabela.getValueAt(linhaSelecionada, 0);
                this.repositorio.deleteById(idParaExcluir);
                JOptionPane.showMessageDialog(this, "Usuário excluído com sucesso!");
                carregarDadosTabela();
            }
        }
    }//GEN-LAST:event_botaoExcluirActionPerformed

    private void tabelaUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaUsuariosMouseClicked
        int linhaSelecionada = tabelaUsuarios.getSelectedRow();
        if (linhaSelecionada >= 0) {
            this.idUsuarioSelecionado = (Long) modeloTabela.getValueAt(linhaSelecionada, 0);
            campoNome.setText(String.valueOf(modeloTabela.getValueAt(linhaSelecionada, 1)));
            campoCpf.setText(String.valueOf(modeloTabela.getValueAt(linhaSelecionada, 2)));
            campoEmail.setText(String.valueOf(modeloTabela.getValueAt(linhaSelecionada, 3)));
        }
    }//GEN-LAST:event_tabelaUsuariosMouseClicked

