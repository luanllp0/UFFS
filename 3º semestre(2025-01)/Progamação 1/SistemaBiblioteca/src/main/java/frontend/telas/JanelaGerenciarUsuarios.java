    private void botaoSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoSalvarActionPerformed
        String nome = campoNome.getText();
        String cpf = campoCpf.getText();
        String email = campoEmail.getText();

        if (nome.isEmpty() || cpf.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Os campos Nome e CPF são obrigatórios.", "Erro de Validação", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (idUsuarioSelecionado == null) {
            Usuario novoUsuario = new Usuario();
            novoUsuario.setNome(nome);
            novoUsuario.setCpf(cpf);
            novoUsuario.setEmail(email);
            
            repositorio.save(novoUsuario);
            JOptionPane.showMessageDialog(this, "Novo usuário salvo com sucesso!");
        } else {
            Usuario usuarioParaAtualizar = repositorio.findById(idUsuarioSelecionado).get();
            usuarioParaAtualizar.setNome(nome);
            usuarioParaAtualizar.setCpf(cpf);
            usuarioParaAtualizar.setEmail(email);
            
            repositorio.save(usuarioParaAtualizar);
            JOptionPane.showMessageDialog(this, "Usuário atualizado com sucesso!");
        }

        campoNome.setText("");
        campoCpf.setText("");
        campoEmail.setText("");
        this.idUsuarioSelecionado = null;
        carregarDadosTabela();
    }//GEN-LAST:event_botaoSalvarActionPerformed

