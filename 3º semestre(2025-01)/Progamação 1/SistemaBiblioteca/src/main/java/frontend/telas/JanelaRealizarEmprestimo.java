    private void botaoConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoConfirmarActionPerformed
        Usuario usuarioSelecionado = (Usuario) comboUsuarios.getSelectedItem();
    Livro livroSelecionado = (Livro) comboLivros.getSelectedItem();

    if (usuarioSelecionado == null || livroSelecionado == null) {
        JOptionPane.showMessageDialog(this, "Por favor, selecione um utilizador e um livro.", "Seleção Inválida", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int resposta = JOptionPane.showConfirmDialog(
        this,
        "Confirma o empréstimo do livro '" + livroSelecionado.getTitulo() + "' para o utilizador '" + usuarioSelecionado.getNome() + "'?",
        "Confirmar Empréstimo",
        JOptionPane.YES_NO_OPTION
    );

    if (resposta == JOptionPane.YES_OPTION) {
        try {
            Emprestimo novoEmprestimo = new Emprestimo();
            novoEmprestimo.setUsuario(usuarioSelecionado);
            novoEmprestimo.setLivro(livroSelecionado);
            novoEmprestimo.setDataEmprestimo(java.time.LocalDate.now()); 
            novoEmprestimo.setDataDevolucaoPrevista(java.time.LocalDate.now().plusWeeks(2)); 

            livroSelecionado.setDisponivel(false);

            this.emprestimoRepo.save(novoEmprestimo); 
            this.livroRepo.save(livroSelecionado);   

            JOptionPane.showMessageDialog(this, "Empréstimo realizado com sucesso!");

            carregarLivrosDisponiveis(); 
            this.dispose(); 

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocorreu um erro ao realizar o empréstimo: " + e.getMessage(), "Erro de Base de Dados", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace(); 
        }
    }        // TODO add your handling code here:
    }//GEN-LAST:event_botaoConfirmarActionPerformed

