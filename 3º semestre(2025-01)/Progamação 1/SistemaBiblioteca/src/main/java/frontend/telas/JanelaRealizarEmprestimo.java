    private void carregarUsuarios() {
        List<Usuario> usuarios = usuarioRepo.findAll();
        comboUsuarios.removeAllItems();
        for (Usuario usuario : usuarios) {
            comboUsuarios.addItem(usuario);
        }
    }

    private void carregarLivrosDisponiveis() {
        List<Livro> livrosDisponiveis = livroRepo.findAll().stream().filter(livro -> livro.isDisponivel()).toList();
        comboLivros.removeAllItems();
        for (Livro livro : livrosDisponiveis) {
            comboLivros.addItem(livro);
        }
    }

